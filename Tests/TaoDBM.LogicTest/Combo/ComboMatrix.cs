using System.Text;
using TaoDBM.Core;
using static TaoDBM.LogicTest.Combo.ComboOps;

namespace TaoDBM.LogicTest.Combo;

/// <summary>
/// COMBO MATRIX RUNNER: full pairwise enumeration of all operations
/// (op pairs) x (both execution orders) x (data states) x (dialects).
/// Each cell either runs for real (attribution = test id CX-nnnnnn)
/// or is marked NOT COMPOSABLE with the engine code-path reason.
/// Emits Docs/ComboMatrix.md so the document always matches the run.
/// </summary>
public static class ComboMatrix
{
    private static string _repoRoot = FindRepoRoot();

    /// <summary>Runs the whole matrix; check(name, ok, detail) is the shared harness sink.</summary>
    public static void RunAll(Action<string, bool, string> check)
    {
        var ops = ComboOps.All();
        var doc = new StringBuilder(1 << 20);
        var nbReasons = new SortedDictionary<string, int>();
        int executed = 0, nb = 0, cellSeq = 0;
        int pairsTotal = ops.Count * (ops.Count - 1) / 2;
        int cell = 0;

        doc.AppendLine("# TAODBM PHASE2 COMBO TEST FULL-COVERAGE MATRIX");
        doc.AppendLine();
        doc.AppendLine($"- Generated by LogicTest ComboMatrix (run UTC: {DateTime.UtcNow:yyyy-MM-ddTHH:mm:ssZ})");
        doc.AppendLine($"- Base: TaoDBM-phase2 main (HEAD 1c79300), branch feat/combo-matrix");
        doc.AppendLine($"- Operations: {ops.Count} (connection menu {ops.Count(o => o.MenuPath == "CONN")}, database menu {ops.Count(o => o.MenuPath == "DB")}, extended {ops.Count(o => o.MenuPath == "EXT")})");
        doc.AppendLine($"- Pairs: {pairsTotal}, orders per pair: 2 (AB and BA), states: {States.Length} (EMPTY/WAN/HUGE/SPC/ILL), dialects: {Dialects.Length} (MYSQL/POSTGRESQL/SQLSERVER/SQLITE)");
        doc.AppendLine($"- Total enumerated cells: {pairsTotal * 2 * States.Length * Dialects.Length}");
        doc.AppendLine();
        doc.AppendLine("## ATTRIBUTION RULES");
        doc.AppendLine();
        doc.AppendLine("1. Cell runs both operations in sequence on a fresh per-cell workspace clone; every op postcondition must hold. Attribution = test id `CX-nnnnnn` (the id is emitted as a named check in the LogicTest run).");
        doc.AppendLine("2. Cell blocked by an engine dialect gate is NOT COMPOSABLE on the real code path; attribution = the reason with the engine source reference (no test exists and none is possible without changing engine support).");
        doc.AppendLine("3. For pairs of PLAN-kind ops (no dataset mutation) the runner additionally asserts order invariance: AB and BA leave identical dataset fingerprints.");
        doc.AppendLine("4. For pairs involving TRANS-kind ops (masking / cleanup / audit / faker) the runner additionally re-executes the AB sequence on a second clone and asserts deterministic fingerprints.");
        doc.AppendLine();
        doc.AppendLine("## OPERATION REGISTRY");
        doc.AppendLine();
        doc.AppendLine("| Id | Menu | Label | Kind | Engine Path |");
        doc.AppendLine("|---|---|---|---|---|");
        foreach (var o in ops)
            doc.AppendLine($"| {o.Id} | {o.MenuPath} | {o.Label} | {o.Kind} | {o.EnginePath} |");
        doc.AppendLine();
        doc.AppendLine("## DATA STATES");
        doc.AppendLine();
        doc.AppendLine("| State | Meaning | Materialized Rows | Declared Caliber |");
        doc.AppendLine("|---|---|---|---|");
        doc.AppendLine("| EMPTY | empty table | 0 | 0 |");
        doc.AppendLine("| WAN | ten-thousand-row table | 10000 | 10000 |");
        doc.AppendLine("| HUGE | tens-of-millions caliber | 500 | 10000000 |");
        doc.AppendLine("| SPC | special characters | 60 | 60 |");
        doc.AppendLine("| ILL | illegal/hostile input | 40 | 40 |");
        doc.AppendLine();
        doc.AppendLine("## PAIR MATRIX");
        doc.AppendLine();

        // iterate unordered pairs
        for (int i = 0; i < ops.Count; i++)
        {
            for (int j = i + 1; j < ops.Count; j++)
            {
                var a = ops[i];
                var b = ops[j];
                cell++;
                doc.AppendLine($"### P{cell:D4} {a.Id}-{a.Label} X {b.Id}-{b.Label}");
                doc.AppendLine();
                doc.AppendLine($"Engines: {a.Id} -> {a.EnginePath} ; {b.Id} -> {b.EnginePath}");
                doc.AppendLine();
                doc.AppendLine("| CellId | Order | State | Dialect | Attribution |");
                doc.AppendLine("|---|---|---|---|---|");

                foreach (var (first, second, order) in new[] { (a, b, "AB"), (b, a, "BA") })
                {
                    foreach (var state in States)
                    {
                        foreach (var eng in Dialects)
                        {
                            cellSeq++;
                            var id = $"CX-{cellSeq:D6}";
                            var g1 = first.Gate(eng);
                            var g2 = second.Gate(eng);
                            if (g1 != null || g2 != null)
                            {
                                nb++;
                                var reason = g1 ?? g2!;
                                nbReasons[reason] = nbReasons.GetValueOrDefault(reason) + 1;
                                doc.AppendLine($"| {id} | {order} | {state} | {DialectName(eng)} | {reason} |");
                                continue;
                            }

                            executed++;
                            var d1 = BuildState(state);
                            var p1 = RunSeq(first, second, d1, eng);
                            var ok1 = p1 == null;

                            // order invariance for non-mutating pairs
                            if (ok1 && first.Kind != "TRANS" && second.Kind != "TRANS")
                            {
                                var d2 = BuildState(state);
                                var p2 = RunSeq(second, first, d2, eng);
                                if (p2 != null) { ok1 = false; p1 = "BA-order problems: " + p2; }
                                else if (d1.Fingerprint() != d2.Fingerprint())
                                { ok1 = false; p1 = $"AB/BA fingerprints diverge (PLAN pair must be order-invariant)"; }
                            }

                            // determinism re-run for mutating pairs
                            if (ok1 && (first.Kind == "TRANS" || second.Kind == "TRANS"))
                            {
                                var d3 = BuildState(state);
                                var p3 = RunSeq(first, second, d3, eng);
                                if (p3 != null) { ok1 = false; p1 = "determinism re-run problems: " + p3; }
                                else if (d1.Fingerprint() != d3.Fingerprint())
                                { ok1 = false; p1 = "same-order rerun fingerprints diverge (nondeterministic transform)"; }
                            }

                            check(id, ok1, p1 ?? $"{first.Id}->{second.Id} {state} {DialectName(eng)}");
                            doc.AppendLine($"| {id} | {order} | {state} | {DialectName(eng)} | OK |");
                        }
                    }
                }
                doc.AppendLine();
            }
        }

        doc.AppendLine("## STATISTICS");
        doc.AppendLine();
        doc.AppendLine($"- Enumerated cells: {cellSeq}");
        doc.AppendLine($"- Executed cells (real tests, attribution = CX ids above): {executed}");
        doc.AppendLine($"- NOT COMPOSABLE cells (gate-blocked, reasons below): {nb}");
        doc.AppendLine();
        doc.AppendLine("### NOT-COMPOSABLE REASONS");
        doc.AppendLine();
        foreach (var (reason, count) in nbReasons)
            doc.AppendLine($"- x{count}: {reason}");
        doc.AppendLine();

        var docPath = Path.Combine(_repoRoot, "Docs", "ComboMatrix.md");
        Directory.CreateDirectory(Path.GetDirectoryName(docPath)!);
        File.WriteAllText(docPath, doc.ToString(), new UTF8Encoding(true));
        check("COMBO-SUMMARY", executed > 0 && cellSeq == executed + nb,
            $"cells={cellSeq} executed={executed} not-composable={nb} doc={docPath}");
    }

    private static string? RunSeq(ComboOp first, ComboOp second, ComboData d, DbEngine eng)
    {
        try
        {
            var p1 = first.Run(d, eng);
            if (p1 != null) return $"{first.Id} problems: {p1}";
        }
        catch (Exception ex)
        {
            return $"{first.Id} threw: {ex.GetType().Name}: {Trunc(ex.Message)}";
        }
        try
        {
            var p2 = second.Run(d, eng);
            if (p2 != null) return $"{second.Id} problems: {p2}";
        }
        catch (Exception ex)
        {
            return $"{second.Id} threw: {ex.GetType().Name}: {Trunc(ex.Message)}";
        }
        return null;
    }

    private static string Trunc(string s) => s.Length <= 200 ? s : s[..200];

    private static string FindRepoRoot()
    {
        var dir = AppContext.BaseDirectory;
        for (int i = 0; i < 8; i++)
        {
            if (File.Exists(Path.Combine(dir, "TaoDBM.slnx"))) return dir;
            dir = Path.GetDirectoryName(dir) ?? dir;
        }
        return Directory.GetCurrentDirectory();
    }
}
